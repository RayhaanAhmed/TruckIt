CREATE TABLE IF NOT EXISTS trucks (
  id VARCHAR(64) PRIMARY KEY,
  plate VARCHAR(32) NOT NULL UNIQUE,
  brand VARCHAR(32) NOT NULL,
  model VARCHAR(64) DEFAULT '',
  engine VARCHAR(64) DEFAULT '',
  year VARCHAR(8) DEFAULT '',
  status VARCHAR(24) DEFAULT 'AT DEPOT',
  active_trip_id VARCHAR(64) DEFAULT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS drivers (
  id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  code VARCHAR(32) DEFAULT 'Code 14 (EC)',
  salary DECIMAL(10, 2) DEFAULT 0.00,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trips (
  id VARCHAR(64) PRIMARY KEY,
  trip_date DATE NOT NULL,
  plate VARCHAR(32) NOT NULL,
  driver_id VARCHAR(64) NOT NULL,
  customer VARCHAR(120) DEFAULT '',
  pickup VARCHAR(120) NOT NULL,
  dropoff VARCHAR(120) NOT NULL,
  km INT NOT NULL DEFAULT 0,
  revenue DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
  fuel_cost DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
  extra_cost DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
  status VARCHAR(24) DEFAULT 'IN TRANSIT',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);